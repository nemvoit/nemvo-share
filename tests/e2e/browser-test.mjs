// Browser tests against the dev container. An administrator creates a share in wp-admin
// (with a file bigger than PHP's upload limit, so it goes up in chunks), then a visitor
// opens it with the password and downloads the file. A burn-after-reading share is
// opened and checked to be gone afterwards. Any console error, uncaught exception or
// unexpected failed request fails the run. Screenshots go to tests/e2e/screenshots/.
//
//   cd tests/e2e && npm install && npm test
//
// BASE (default http://localhost:8070) and CHROME (path to Chrome) can be set in the environment.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';

const here = dirname(fileURLToPath(import.meta.url));
const BASE = process.env.BASE || 'http://localhost:8070';
const CHROME = process.env.CHROME || ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].find((p) => existsSync(p));
const SHOTS = join(here, 'screenshots');
mkdirSync(SHOTS, { recursive: true });

let failed = 0;
const ok = (cond, msg) => {
	console.log((cond ? 'ok   ' : 'FAIL ') + msg);
	if (!cond) {
		failed++;
	}
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const wp = (...args) => execFileSync('docker', ['compose', '-f', join(here, '../../.devcontainer/docker-compose.yml'), 'exec', '-T', 'wordpress', 'wp', ...args], { encoding: 'utf8' }).trim();
const shot = (page, name, full = true) => page.screenshot({ path: join(SHOTS, name + '.png'), fullPage: full });

// Responses that are expected for a page (e.g. 410 for a burned share).
function watch(page, label, problems, allow = () => false) {
	page.on('console', (m) => m.type() === 'error' && !/the server responded with a status of 410/.test(m.text()) && problems.push(`${label}: console: ${m.text()}`));
	page.on('pageerror', (e) => problems.push(`${label}: exception: ${e.message}`));
	page.on('requestfailed', (r) => !/favicon/.test(r.url()) && !/net::ERR_ABORTED/.test(r.failure()?.errorText || '') && problems.push(`${label}: request failed: ${r.url()} ${r.failure()?.errorText}`));
	page.on('response', (r) => r.status() >= 400 && !/favicon/.test(r.url()) && !allow(r) && problems.push(`${label}: HTTP ${r.status()} ${r.url()}`));
}

// Test files: a small "PDF" and a 9 MB archive (more than PHP's default 2 MB limit).
const work = join(tmpdir(), 'nemvo-share-e2e');
mkdirSync(work, { recursive: true });
const small = join(work, 'Quarterly report Q3.pdf');
const big = join(work, 'Design files – final.zip');
writeFileSync(small, randomBytes(312_000));
writeFileSync(big, randomBytes(9_400_000));

const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ['--window-size=1440,1000', '--no-first-run'] });
const problems = [];
try {
	/* ---------------- Administrator ---------------- */
	const adminCtx = await browser.createBrowserContext();
	const admin = await adminCtx.newPage();
	watch(admin, 'admin', problems);
	await admin.setViewport({ width: 1440, height: 1000 });
	await admin.goto(`${BASE}/wp-login.php`);
	await admin.type('#user_login', 'admin');
	await admin.type('#user_pass', 'admin');
	await Promise.all([admin.waitForNavigation(), admin.click('#wp-submit')]);

	await admin.goto(`${BASE}/wp-admin/admin.php?page=nemvo-share`);
	await shot(admin, 'admin-list');
	ok(await admin.$('.wp-list-table'), 'share list renders');

	await admin.goto(`${BASE}/wp-admin/admin.php?page=nemvo-share-new`);
	await shot(admin, 'admin-new-empty');
	ok((await admin.$eval('#nvs-limits', (e) => e.textContent)).includes('per file'), 'upload limits are shown');
	const generated = await admin.$eval('#nvs-password', (e) => e.value);
	ok(/^[A-Za-z0-9]{4}(-[A-Za-z0-9]{4}){3}$/.test(generated), `a password is generated by default (${generated})`);

	await admin.type('#nvs-title', 'Design hand-off for Acme');
	await admin.type('#nvs-note', 'Hi Anna,\n\nHere are the final design files and the Q3 report.\nFigma: https://figma.example/acme\nLogin: anna@acme.example / Vt7k-Wq2m\n\nCheers!');

	// Throttle uploads so the progress bar can be seen.
	const cdp = await admin.createCDPSession();
	await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 20, downloadThroughput: -1, uploadThroughput: 3 * 1024 * 1024 });
	const input = await admin.$('#nvs-file-input');
	await input.uploadFile(small, big);
	await admin.waitForSelector('.nvs-fileitem.is-uploading');
	await sleep(1600);
	await shot(admin, 'admin-uploading');
	const barWidth = await admin.$eval('.nvs-fileitem.is-uploading .nvs-progress-bar', (b) => b.getBoundingClientRect().width).catch(() => 0);
	ok(barWidth > 0, `the progress bar fills while uploading (${Math.round(barWidth)} px)`);
	ok(await admin.$eval('#nvs-submit', (b) => b.disabled), 'saving waits for the uploads');
	await admin.waitForFunction(() => document.querySelectorAll('#nvs-uploads .nvs-fileitem.is-done').length === 2, { timeout: 60000 });
	await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
	ok(true, 'both files uploaded in chunks');
	await shot(admin, 'admin-uploaded');

	await Promise.all([admin.waitForNavigation(), admin.click('#nvs-submit')]);
	ok(await admin.$('.nvs-linkpanel.is-created'), 'the share is created and its link shown');
	const link = await admin.$eval('#nvs-link', (e) => e.value);
	const password = await admin.$eval('#nvs-link-password', (e) => e.value);
	ok(/\/share\/[A-Za-z0-9]{24}\/$/.test(link), `link looks like /share/<secret>/ (${link})`);
	ok(password === generated, 'the generated password was saved');
	await shot(admin, 'admin-created');

	/* ---------------- Visitor ---------------- */
	const visitorCtx = await browser.createBrowserContext();
	const visitor = await visitorCtx.newPage();
	watch(visitor, 'visitor', problems);
	await visitor.setViewport({ width: 1280, height: 900 });
	await visitor.goto(link);
	ok(await visitor.$('#nvs-password'), 'visitor is asked for the password');
	const title = 'Design hand-off for Acme';
	const titleHidden = async (when) => {
		const html = await visitor.content();
		const heading = await visitor.$$eval('h1, h2', (els) => els.map((e) => e.textContent.trim()).join(' | '));
		ok(!html.includes(title) && (await visitor.title()).startsWith('Protected share') && heading.includes('Protected share'), `the title is hidden ${when} (heading: ${heading}; tab: ${await visitor.title()})`);
	};
	await titleHidden('before the password');
	await shot(visitor, 'visitor-password');

	await visitor.type('#nvs-password', 'wrong-password');
	await Promise.all([visitor.waitForNavigation(), visitor.click('.nvs-form button[type="submit"]')]);
	ok(await visitor.$('.nvs-error'), 'a wrong password shows an error');
	await titleHidden('after a wrong password');
	await shot(visitor, 'visitor-wrong-password');

	await visitor.type('#nvs-password', password);
	await Promise.all([visitor.waitForNavigation(), visitor.click('.nvs-form button[type="submit"]')]);
	const note = await visitor.$eval('#nvs-note-text', (e) => e.textContent).catch(() => '');
	ok(note.includes('Vt7k-Wq2m'), 'the note is shown after the right password');
	const names = await visitor.$$eval('.nvs-file-name', (els) => els.map((e) => e.textContent));
	ok(names.length === 2 && names.includes('Design files – final.zip'), `files are listed (${names.join(', ')})`);
	ok((await visitor.title()).startsWith(title), 'the browser tab shows the share title after the password');
	ok((await visitor.$$eval('h1, h2', (els) => els.map((e) => e.textContent).join(' '))).includes(title), 'the page heading shows the share title after the password');
	await shot(visitor, 'visitor-open');

	// Download the big file through the page's own link and compare the size.
	const href = await visitor.$$eval('.nvs-download', (as) => as.map((a) => a.href));
	const size = await visitor.evaluate(async (url) => (await (await fetch(url)).arrayBuffer()).byteLength, href[1]);
	ok(size === statSync(big).size, `download is complete (${size} bytes)`);

	// The same download link without the cookie: 403 with the password form, still without the title.
	const locked = await fetch(href[1], { redirect: 'manual' });
	const lockedHtml = await locked.text();
	ok(locked.status === 403 && lockedHtml.includes('nemvo_share_password') && !lockedHtml.includes(title), `a download without the password gets the form, not the title (${locked.status})`);

	await visitor.setViewport({ width: 390, height: 844, isMobile: true });
	await visitor.reload();
	await shot(visitor, 'visitor-open-mobile');

	/* ---------------- Burn after reading ---------------- */
	const burnUrl = wp('nemvo-share', 'create', '--title=Server credentials', '--note=root / Zx9q-Lm4w-Tt7p-Hc2v', '--burn', '--expires=1d', '--porcelain');
	const burnCtx = await browser.createBrowserContext();
	const burner = await burnCtx.newPage();
	const burnProblems = [];
	watch(burner, 'burn', burnProblems, (r) => r.status() === 410);
	await burner.setViewport({ width: 1280, height: 900 });
	await burner.goto(burnUrl);
	ok(!(await burner.$('#nvs-note-text')), 'a burn-after-reading share is not shown before Open');
	await shot(burner, 'visitor-burn-confirm');
	await Promise.all([burner.waitForNavigation(), burner.click('.nvs-form button[type="submit"]')]);
	ok((await burner.$eval('#nvs-note-text', (e) => e.textContent)).includes('Zx9q'), 'the note is shown once');
	await shot(burner, 'visitor-burn-open');
	const again = await burner.goto(burnUrl);
	ok(again.status() === 410, 'afterwards the link answers 410 Gone');
	await shot(burner, 'visitor-burn-gone');
	problems.push(...burnProblems);

	const missing = await burner.goto(`${BASE}/share/AAAAAAAAAAAAAAAAAAAAAAAA/`);
	ok(missing.status() === 404, 'an unknown link answers 404');

	/* ---------------- Back in wp-admin ---------------- */
	await admin.reload();
	await shot(admin, 'admin-edit-activity');
	const activity = await admin.$$eval('.nvs-activity-text', (els) => els.map((e) => e.textContent));
	ok(activity.some((t) => /Downloaded/.test(t)) && activity.some((t) => /Wrong password/.test(t)), 'activity shows the download and the wrong password');
	await admin.goto(`${BASE}/wp-admin/admin.php?page=nemvo-share`);
	await shot(admin, 'admin-list-after');
	await admin.goto(`${BASE}/wp-admin/admin.php?page=nemvo-share-settings`);
	await shot(admin, 'admin-settings');
} finally {
	await browser.close();
}

for (const p of problems) {
	ok(false, p);
}
console.log(failed ? `\n${failed} FAILED` : '\nBROWSER TEST PASSED');
process.exit(failed ? 1 : 0);
